## What it means for Connecticut renters

Connecticut cities weren't broken out in this study. Still, the Northeast pattern is worth remembering: in dense, transit-friendly areas, you often trade space for location. Many Connecticut rentals are also in older multi-family houses, where layouts vary a lot from one home to the next.

## Tips for judging space when you tour

1. **Ask for the square footage** and how it was measured, then compare price per square foot between homes.
2. **Bring a tape measure** or use your phone to check where your bed, couch and desk will go.
3. **Count the closets and storage.** A smaller home with good storage can feel bigger than a larger one without it.
4. **Look at the layout, not just the number.** Long hallways count toward square footage but aren't living space.

