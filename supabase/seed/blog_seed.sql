## How RentCafe measures "competitive"

RentCafe's **Rental Competitiveness Index (RCI)** uses Yardi data for 139 large markets. It combines five things:

- how many people competed for each available apartment
- how many renters renewed their lease instead of moving
- how many days a vacant apartment took to fill
- the share of apartments that were occupied
- the share of apartments that were newly built

A higher score means a tougher market for renters.

## The national picture

RentCafe's numbers show the market easing slightly from last summer:

- The national score dipped to **73.9** (from 74.6 a year earlier).
- About **9 renters** competed for each vacant apartment.
- Apartments took **42 days** to fill on average.
- Newly built apartments made up just **0.5%** of rentals, down from 0.8%.

The last point is the catch. With fewer new buildings opening, some markets are still very tight even as others cool down.

## Chicago takes the top spot

RentCafe ranks **Chicago** as the most competitive market, with a score of 91.8 and about 17 prospective renters per vacancy. **Miami**, which led earlier in the season, is now second. RentCafe also says **Manhattan** moved into the top five large markets.

