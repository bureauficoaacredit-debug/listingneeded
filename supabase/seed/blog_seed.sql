RentCafe's study covered the 100 largest U.S. cities. **Tallahassee, FL** has the largest new apartments, averaging about 1,156 sq. ft. It's followed by **Gainesville, FL**, **Baton Rouge, LA**, **Knoxville, TN** and **Fort Myers, FL**.

