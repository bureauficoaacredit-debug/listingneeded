## Why high earners choose to rent

RentCafe lists a few reasons, and they apply to many renters, not only wealthy ones:

- **Flexibility.** Renting makes it easier to relocate for work without the time and cost of selling a house.
- **Keeping money liquid.** Some people would rather invest their savings than tie it up in a down payment.
- **Remote work.** The pandemic pushed many people to move to places with lower costs or taxes. RentCafe highlights Houston, where millionaire renter households grew about 13-fold.

## Who they are

RentCafe reports that nearly half (49%) of millionaire renters are Millennials. Gen Z is still a tiny share, but it's the fastest-growing group. Most work in high-paying office jobs such as executives, tech professionals and financial managers.

## Where Connecticut fits

Connecticut shows up in the report more than once:

- **Hartford** is on RentCafe's list of metros that had no millionaire renter households in 2020 and about 35 by 2024.
- **Bridgeport** (the Fairfield County metro) ranks 10th nationally for millionaire renter households, with about 269 in 2024. It ranks 9th for millionaire homeowner households.
- Nearby, the **New York** metro remains the top market by far.

## What it means if you rent or sell in CT

For everyday renters, more well-paid people choosing to rent adds competition for the nicest rentals, especially in Fairfield County near the train lines into New York. If you see a home you like, be ready to apply: have pay stubs, references and a photo ID on hand.

For owners, it's a reminder that a well-kept rental in a good location attracts strong applicants. Clear photos, an honest description and a quick reply to inquiries go a long way.

